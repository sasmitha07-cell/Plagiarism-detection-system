  /// Detect missing citations in text
  Future<List<Map<String, dynamic>>> detectMissingCitations(
    String text,
  ) async {
    final prompt = '''
Analyze this academic text and identify statements that need citations but lack them.

Text:
"""
$text
"""

Respond ONLY with valid JSON array:
[
  {
    "statement": "<text that needs citation>",
    "reason": "<why it needs a citation>",
    "suggested_search": "<search query to find appropriate source>"
  }
]
''';

    try {
      final response = await model.generateContent([Content.text(prompt)]);
      final responseText = response.text ?? '[]';
      final jsonStr = _extractJsonArray(responseText);
      return (jsonDecode(jsonStr) as List<dynamic>)
          .map((e) => e as Map<String, dynamic>)
          .toList();
    } catch (e) {
      return [];
    }
  }

  /// Compare two documents
  Future<Map<String, dynamic>> compareDocuments(
    String textA,
    String textB,
    String titleA,
    String titleB,
  ) async {
    final prompt = '''
Compare these two documents for similarity, plagiarism, and overlap.

Document A ($titleA):
"""
${textA.length > 3000 ? textA.substring(0, 3000) : textA}
"""

Document B ($titleB):
"""
${textB.length > 3000 ? textB.substring(0, 3000) : textB}
"""

Respond ONLY with valid JSON:
{
  "overall_similarity": <0-100>,
  "exact_match_percentage": <0-100>,
  "semantic_similarity_percentage": <0-100>,
  "paraphrase_percentage": <0-100>,
  "matched_sections": [
    {
      "text_a": "<section from doc A>",
      "text_b": "<matching section from doc B>",
      "similarity_type": "<exact|semantic|paraphrase>",
      "similarity_score": <0-100>
    }
  ],
  "executive_summary": "<overall comparison analysis>",
  "unique_to_a": ["<unique concept/section in A>"],
  "unique_to_b": ["<unique concept/section in B>"]
}
''';

    try {
      final response = await model.generateContent([Content.text(prompt)]);
      final responseText = response.text ?? '{}';
      print('GeminiService: Received quality analysis response');
      final jsonStr = _extractJson(responseText);
      return jsonDecode(jsonStr) as Map<String, dynamic>;
    } catch (e) {
      print('GeminiService Error (Quality): $e');
      return {
        'overall_similarity': 0,
        'exact_match_percentage': 0,
        'semantic_similarity_percentage': 0,
        'paraphrase_percentage': 0,
        'matched_sections': [],
        'executive_summary': 'Comparison failed. Please try again.',
        'unique_to_a': [],
        'unique_to_b': [],
      };
    }
  }

  // Helper to extract JSON from model response
  String _extractJson(String text) {
    final jsonStart = text.indexOf('{');
    final jsonEnd = text.lastIndexOf('}');
    if (jsonStart != -1 && jsonEnd != -1 && jsonEnd > jsonStart) {
      return text.substring(jsonStart, jsonEnd + 1);
    }
    return text.trim();
  }

  String _extractJsonArray(String text) {
    final jsonStart = text.indexOf('[');
    final jsonEnd = text.lastIndexOf(']');
    if (jsonStart != -1 && jsonEnd != -1 && jsonEnd > jsonStart) {
      return text.substring(jsonStart, jsonEnd + 1);
    }
    return '[]';
  }
}
