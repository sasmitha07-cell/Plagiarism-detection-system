import 'dart:convert';
import 'package:google_generative_ai/google_generative_ai.dart';
import '../constants/app_constants.dart';

class GeminiService {
  static GeminiService? _instance;
  GenerativeModel? _model;

  GeminiService._();

  static GeminiService get instance {
    _instance ??= GeminiService._();
    return _instance!;
  }

  void initialize(String apiKey) {
    _model = GenerativeModel(
      model: AppConstants.geminiModel,
      apiKey: apiKey,
      generationConfig: GenerationConfig(
        temperature: 0.3,
        topK: 40,
        topP: 0.95,
        maxOutputTokens: 8192,
      ),
    );
  }

  GenerativeModel get model {
    if (_model == null) {
      throw StateError(
        'GeminiService not initialized. Call initialize(apiKey) first.',
      );
    }
    return _model!;
  }

  /// Analyze text for AI content detection
  Future<Map<String, dynamic>> detectAiContent(String text) async {
    print('GeminiService: Starting AI content detection');
    final prompt = '''
Analyze the following text and determine if it was written by a human or generated by AI.

Text to analyze:
"""
$text
"""

Respond ONLY with valid JSON in this exact format:
{
  "human_score": <0-100>,
  "ai_score": <0-100>,
  "confidence": <0-100>,
  "content_type": "<human|ai|mixed>",
  "reasoning": "<brief explanation>",
  "ai_indicators": ["<indicator1>", "<indicator2>"],
  "human_indicators": ["<indicator1>", "<indicator2>"]
}

Scoring guidelines:
- human_score + ai_score = 100
- content_type is "human" if ai_score < 30, "ai" if ai_score > 70, "mixed" otherwise
- confidence is how certain you are (0-100)
''';

    try {
      final response = await model.generateContent([Content.text(prompt)]);
      final textResponse = response.text ?? '{}';
      print('GeminiService: Received AI detection response');
      final jsonStr = _extractJson(textResponse);
      return jsonDecode(jsonStr) as Map<String, dynamic>;
    } catch (e) {
      print('GeminiService Error (AI Detection): $e');
      return {
        'human_score': 70,
        'ai_score': 30,
        'confidence': 50,
        'content_type': 'human',
        'reasoning': 'Unable to analyze content at this time.',
        'ai_indicators': [],
        'human_indicators': [],
      };
    }
  }

