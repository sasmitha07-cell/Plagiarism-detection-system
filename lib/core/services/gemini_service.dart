  /// Detect plagiarism semantically and explain flagged sections
  Future<Map<String, dynamic>> analyzeForPlagiarism(
    String text,
    List<Map<String, dynamic>> webSources,
  ) async {
    print('GeminiService: Starting plagiarism analysis');
    final sourcesJson = jsonEncode(webSources.take(10).toList());

    final prompt = '''
You are an expert plagiarism detection system. Analyze the following text against the provided web sources and your internal knowledge of the web.

CRITICAL INSTRUCTIONS:
1. If the text is a direct copy from a common website (like Google, Wikipedia, or news articles), the "overall_similarity_score" MUST be near 100%.
2. Identify the specific sources where this text appears.
3. Be strict. Paraphrasing that keeps the same structure should still be flagged with a high score.

Text to analyze:
"""
$text
"""

Web sources found (URL, snippet):
$sourcesJson

For each suspicious section in the text, determine:
1. Is it an exact copy, partial copy, paraphrase, or semantic similarity?
2. What is the risk level?
3. What is the confidence score?
4. Provide a clear explanation.

Respond ONLY with valid JSON:
{
  "overall_similarity_score": <0-100>,
  "exact_match_score": <0-100>,
  "semantic_similarity_score": <0-100>,
  "paraphrase_score": <0-100>,
  "flagged_sections": [
    {
      "start_position": <char_offset>,
      "end_position": <char_offset>,
      "flagged_text": "<exact text from original>",
      "plagiarism_type": "<exact_copy|partial_copy|semantic_similarity|missing_citation|paraphrased|ai_rewritten>",
      "risk_level": "<safe|low|medium|high|critical>",
      "confidence_score": <0-100>,
      "similarity_score": <0-100>,
      "source_url": "<url>",
      "source_title": "<title>",
      "matched_source_text": "<matching text from source>",
      "explanation": "<why this is flagged>",
      "suggested_action": "<what user should do>"
    }
  ],
  "executive_summary": "<overall assessment>",
  "recommendations": ["<actionable recommendation>"]
}
''';

    try {
      final response = await model.generateContent([Content.text(prompt)]);
      final responseText = response.text ?? '{}';
      print('GeminiService: Received plagiarism response');
      final jsonStr = _extractJson(responseText);
      return jsonDecode(jsonStr) as Map<String, dynamic>;
    } catch (e) {
      print('GeminiService Error (Plagiarism): $e');
      return {
        'overall_similarity_score': 0,
        'exact_match_score': 0,
        'semantic_similarity_score': 0,
        'paraphrase_score': 0,
        'flagged_sections': [],
        'executive_summary': 'Analysis could not be completed at this time.',
        'recommendations': ['Please try again.'],
      };
    }
  }

